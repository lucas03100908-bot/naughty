// Bakes the cobbled ground's height into a grid matching the snow heightfield, so snow lies on
// the street (not under it) and buildings can be set on the pavement.
//   node scripts/ground-heights.mjs      (re-run after changing GROUND in src/scene/layout.ts)
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import fs from 'node:fs';
import { GROUND } from '../src/scene/layout.ts';
import { GLOBE, SNOW } from '../src/game/constants.ts';

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc = await io.read('assets/source/ground.glb');
const N = SNOW.grid;
const Rf = GLOBE.floorRadius;
const cell = (2 * Rf) / N;
const grid = new Float32Array(N * N).fill(-1);
const c = Math.cos(GROUND.rotationY);
const s = Math.sin(GROUND.rotationY);
for (const mesh of doc.getRoot().listMeshes())
  for (const prim of mesh.listPrimitives()) {
    const a = prim.getAttribute('POSITION').getArray();
    for (let i = 0; i < a.length; i += 3) {
      const x = a[i] * GROUND.scale, y = a[i + 1] * GROUND.scale, z = a[i + 2] * GROUND.scale;
      const gx = c * x + s * z + GROUND.position[0];
      const gz = -s * x + c * z + GROUND.position[2];
      if (Math.hypot(gx, gz) > GROUND.clipRadius) continue;
      const ix = Math.floor((gx + Rf) / cell), iz = Math.floor((gz + Rf) / cell);
      if (ix < 0 || iz < 0 || ix >= N || iz >= N) continue;
      const k = iz * N + ix;
      grid[k] = Math.max(grid[k], y + GROUND.position[1]);
    }
  }
const out = Array.from(grid, (v) => Math.round(v * 10000) / 10000);
fs.writeFileSync(
  'src/scene/groundHeights.ts',
  `// Generated by scripts/ground-heights.mjs from assets/source/ground.glb and GROUND in layout.ts. Do not edit.\n// Height of the cobbled ground per snow cell (globe-local, above the floor); -1 = no ground.\nexport const GROUND_HEIGHTS = { n: ${N}, radius: ${Rf}, heights: [${out.join(',')}] };\n`,
);
const covered = out.filter((v) => v >= 0).length;
console.log(`ground heights: ${N}×${N}, ${covered} cells covered, max ${Math.max(...out).toFixed(3)}`);
